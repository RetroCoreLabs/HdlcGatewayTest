namespace HdlcGatewayTest.Gateway;

/// <summary>
/// The job of one pane (Ronny, 2026-11-08). The console and the frame list work in every role;
/// the role only decides where a received data frame goes next. Control frames (address 0xFE)
/// are never echoed, bridged or forwarded.
/// </summary>
public enum GatewayRole
{
    /// <summary>Commands to the firmware, replies and log; received frames are only listed.</summary>
    Console,

    /// <summary>A raw frame terminal: paste hex, send it; everything received is listed.</summary>
    Free,

    /// <summary>Every data frame received is sent straight back out on the same port.</summary>
    Echo,

    /// <summary>A data frame received here is sent on the other pane's port, and the other way round.</summary>
    Bridge,

    /// <summary>Also listen on a TCP port; frames from the TCP peer go to the serial line and back.</summary>
    TcpListen,

    /// <summary>
    /// Also connect OUT to a TCP server (an nd100 emulator that listens): frames from the line go
    /// to it and its frames go to the line (Ronny, 2026-11-09: pane A is the Pico, forwarded to
    /// the emulator at 192.168.1.180).
    /// </summary>
    TcpClient,
}

/// <summary>Where a frame record came from or went to.</summary>
public enum FrameSource
{
    /// <summary>The gateway's serial port (the HDLC line behind it).</summary>
    Serial,

    /// <summary>The TCP peer of a TcpListen pane.</summary>
    Tcp,

    /// <summary>Sent back by the Echo role.</summary>
    Echo,

    /// <summary>Forwarded from the other pane by the Bridge role.</summary>
    Bridge,

    /// <summary>Typed or pasted in the pane's console or hex box.</summary>
    Console,

    /// <summary>Issued by an AI client over MCP.</summary>
    Mcp,

    /// <summary>Generated by the traffic test.</summary>
    Traffic,
}

/// <summary>Lifecycle of a pane's connection to its gateway.</summary>
public enum GatewaySessionState
{
    /// <summary>No transport.</summary>
    Disconnected,

    /// <summary>Opening the transport.</summary>
    Connecting,

    /// <summary>HELLO sent, waiting; then the text console if needed.</summary>
    Probing,

    /// <summary>Connected; commands go as control frames.</summary>
    ControlFrames,

    /// <summary>Connected; commands go through the legacy text console.</summary>
    TextConsole,

    /// <summary>Connected, but nothing answered; raw terminal only.</summary>
    Unknown,

    /// <summary>
    /// Connected to a frames-only endpoint (a gateway over TCP in WiFi mode, or nd100x): frames
    /// flow and are listed, commands are not possible here (the gateway's go over USB).
    /// </summary>
    FramesOnly,

    /// <summary>The transport failed; reconnect to continue.</summary>
    Faulted,
}
